#!/usr/bin/env node
/**
 * build — turns `web/` (source) into `web/dist/` (deployable static site).
 *
 * There is no framework and no dependency: the source files are plain "classic" scripts, so the
 * build only has to
 *   1. read the <script src="..."> list from web/index.html (the single source of truth for the
 *      load order — the dev page and the bundle can never drift apart),
 *   2. concatenate those files into one `sirisphere.js` (with freshly generated shader sources,
 *      so a change to the Android shaders is always included),
 *   3. rewrite index.html to load that single file,
 *   4. copy styles.css and the assets/ folder, and write version.json + .nojekyll.
 *
 * Usage:
 *   node tools/build.mjs            # build dist/  (monorepo: node web/tools/build.mjs)
 *   node tools/build.mjs --clean    # remove dist/ first
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, statSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, basename } from 'node:path';
import { createHash } from 'node:crypto';
import { renderShaderModule, readShaders, WEB_DIR, MONOREPO } from './sync-shaders.mjs';

// Label prefix for log/error messages: this folder may be checked out standalone (repo root)
// or inside the SiriSphere monorepo (where everything is prefixed with web/).
const P = MONOREPO ? 'web/' : '';

const INDEX = join(WEB_DIR, 'index.html');
const CSS = join(WEB_DIR, 'styles.css');
const DIST = join(WEB_DIR, 'dist');
const SCRIPTS_START = '<!-- siri:scripts:start -->';
const SCRIPTS_END = '<!-- siri:scripts:end -->';

const VERSION = '1.0.0';

function fail(message) {
    console.error('FAIL  ' + message);
    process.exit(1);
}

/** Reads the dev page and returns { html, scripts: string[] } (paths relative to web/). */
function readPage() {
    if (!existsSync(INDEX)) fail(`missing ${P}index.html`);
    const html = readFileSync(INDEX, 'utf8').replace(/\r\n/g, '\n');
    const from = html.indexOf(SCRIPTS_START);
    const to = html.indexOf(SCRIPTS_END);
    if (from < 0 || to < 0 || to < from) {
        fail(`${P}index.html must contain "${SCRIPTS_START}" ... "${SCRIPTS_END}" around the dev <script> tags`);
    }
    const block = html.slice(from, to);
    const scripts = [...block.matchAll(/<script[^>]+src=["']([^"']+)["']/g)].map(m => m[1]);
    if (!scripts.length) fail('no <script src="..."> found between the siri:scripts markers');
    return { html, scripts, from, to };
}

function bundle() {
    const { html, scripts, from, to } = readPage();
    const chunks = [];
    let bytes = 0;

    // 1. shaders, freshly generated from the Android assets
    const shaderModule = renderShaderModule();
    chunks.push(shaderModule);
    bytes += Buffer.byteLength(shaderModule);

    // 2. every script listed in the dev page, in that order
    for (const src of scripts) {
        if (src === 'src/shaders.generated.js') continue;                 // already inlined above
        const path = join(WEB_DIR, src);
        if (!existsSync(path)) fail(`${P}index.html references a missing file: ${src}`);
        const code = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
        chunks.push(`\n/* ============================================================ ${src} */\n`);
        chunks.push(code);
        bytes += Buffer.byteLength(code);
    }

    const banner =
        `/*! SiriSphere web ${VERSION} — ${new Date().toISOString()}\n` +
        ` *  Generated by ${P}tools/build.mjs from ${scripts.length} scripts; do not edit.\n` +
        ` *  Shaders: ${readShaders().hash} (verbatim from siri-sphere/src/main/assets/siri_sphere/)\n` +
        ` */\n`;
    const js = banner + chunks.join('');

    // 3. the deployed page loads the single bundle instead of the dev modules
    const deployed = html.slice(0, from) +
        SCRIPTS_START + '\n    <script src="sirisphere.js"></script>\n    ' + SCRIPTS_END +
        html.slice(to + SCRIPTS_END.length);

    return { js, html: deployed, scripts };
}

function dirSize(dir) {
    let total = 0;
    for (const entry of readdirSync(dir)) {
        const path = join(dir, entry);
        const s = statSync(path);
        total += s.isDirectory() ? dirSize(path) : s.size;
    }
    return total;
}

/** Recursive copy (web/assets/** is small and there is no dependency to lean on). */
function copyDir(from, to) {
    mkdirSync(to, { recursive: true });
    for (const entry of readdirSync(from)) {
        const src = join(from, entry);
        const dst = join(to, entry);
        if (statSync(src).isDirectory()) copyDir(src, dst);
        else writeFileSync(dst, readFileSync(src));
    }
}

function main() {
    if (process.argv.includes('--clean') && existsSync(DIST)) rmSync(DIST, { recursive: true, force: true });
    mkdirSync(DIST, { recursive: true });

    const { js, html, scripts } = bundle();
    writeFileSync(join(DIST, 'sirisphere.js'), js, 'utf8');
    writeFileSync(join(DIST, 'index.html'), html, 'utf8');
    if (!existsSync(CSS)) fail(`missing ${P}styles.css`);
    writeFileSync(join(DIST, 'styles.css'), readFileSync(CSS, 'utf8'), 'utf8');
    const assets = join(WEB_DIR, 'assets');
    if (existsSync(assets)) copyDir(assets, join(DIST, 'assets'));
    const smoke = join(WEB_DIR, 'tools', 'smoke.html');
    if (existsSync(smoke)) writeFileSync(join(DIST, 'smoke.html'), readFileSync(smoke, 'utf8'), 'utf8');  // diagnostics page
    writeFileSync(join(DIST, '.nojekyll'), '');                           // keep GitHub Pages from running Jekyll

    const meta = {
        name: 'sirisphere-web',
        version: VERSION,
        builtAt: new Date().toISOString(),
        shaders: readShaders().hash,
        bundle: { file: 'sirisphere.js', bytes: Buffer.byteLength(js), scripts: scripts.length, sha256: createHash('sha256').update(js).digest('hex') }
    };
    writeFileSync(join(DIST, 'version.json'), JSON.stringify(meta, null, 2) + '\n', 'utf8');

    const kb = n => (n / 1024).toFixed(1) + ' kB';
    console.log(`OK    ${P}dist/index.html      ${kb(statSync(join(DIST, 'index.html')).size)}`);
    console.log(`OK    ${P}dist/sirisphere.js   ${kb(meta.bundle.bytes)}  (${scripts.length} scripts, shaders ${meta.shaders})`);
    console.log(`OK    ${P}dist/styles.css      ${kb(statSync(join(DIST, 'styles.css')).size)}`);
    console.log(`OK    ${P}dist/version.json`);
    console.log(`      total ${kb(dirSize(DIST))} — ready to serve (GitHub Pages, any static host, or file://)`);
    console.log(`      ${basename(INDEX)} in dev keeps using the individual scripts in ${P}src/.`);
}

main();
